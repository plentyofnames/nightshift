// '#'/'.' text → 32 rows of 128 pixels
export const rowsOf = (text) => {
  const lines = text.trim().split('\n');
  return Array.from({ length: 32 }, (_, y) => Array.from({ length: 128 }, (_, x) => (lines[y]?.[x] === '#' ? 1 : 0)));
};
